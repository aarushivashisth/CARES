import fs from 'node:fs';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { config } from '../config/env.js';
import { postgresSql } from './database.js';
export async function migrate(client) {
  const tracking=await client.query("SELECT table_name FROM information_schema.tables WHERE table_schema='public' AND table_name IN ('users','schema_migrations')");
  if (tracking.rows.some(r=>r.table_name==='users') && !tracking.rows.some(r=>r.table_name==='schema_migrations')) throw new Error('Refusing unversioned existing database; requires a separately reviewed adoption/migration.');
  await client.query('BEGIN');
  try {
    await client.query('SELECT pg_advisory_xact_lock(10439871)');
    await client.query('CREATE TABLE IF NOT EXISTS schema_migrations (version TEXT PRIMARY KEY, checksum TEXT NOT NULL, applied_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP)');
    for (const file of ['001_postgres.sql','002_home_care.sql','003_rate_limits.sql']) {
      let sql=fs.readFileSync(new URL(`./migrations/${file}`,import.meta.url),'utf8');
      const checksum=crypto.createHash('sha256').update(sql).digest('hex');
      const previous=(await client.query('SELECT checksum FROM schema_migrations WHERE version=$1',[file])).rows[0];
      if (previous) { if(previous.checksum!==checksum) throw new Error('Previously applied migration checksum mismatch.'); continue; }
      if (file!=='001_postgres.sql') sql=postgresSql(sql).replaceAll('INTEGER PRIMARY KEY AUTOINCREMENT','INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY');
      await client.query(sql);
      await client.query('INSERT INTO schema_migrations (version,checksum) VALUES ($1,$2)',[file,checksum]);
    }
    await client.query('COMMIT');
  } catch(err) { await client.query('ROLLBACK'); throw err; }
}
if (process.argv[1]===fileURLToPath(import.meta.url)) {
  if (!process.argv.includes('--confirm-migrations') || !config.databaseUrl) throw new Error('Explicit DATABASE_URL and --confirm-migrations required. Target must be owner-approved; no automatic startup migrations.');
  const { Client }=await import('pg');
  const client=new Client({connectionString:config.databaseUrl,connectionTimeoutMillis:5000});
  try { await client.connect(); await migrate(client); console.log('Versioned PostgreSQL migrations applied. No records imported.'); }
  catch { console.error('Migration failed. Inspect target and migration versions privately. No credentials logged.'); process.exitCode=1; }
  finally { await client.end(); }
}
